create table private.team_memos(
 id bigint generated by default as identity primary key,
 date date not null,
 memo text not null check(char_length(memo)<=500),
 owner_team text check(owner_team in ('A','B','C','D')),
 created_by text,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(),
 revision bigint not null default 1,
 unique(date,owner_team)
);
alter table private.team_memos enable row level security;
revoke all on private.team_memos from public,anon,authenticated;
revoke all on sequence private.team_memos_id_seq from public,anon,authenticated;
-- Keep daily_memos intact as a legacy snapshot. Copy content without emitting new history events.
insert into private.team_memos(date,memo,owner_team,created_by,created_at,updated_at)
select m.date,m.memo,(select max(u.team) from public.app_users u where u.name=m.created_by and u.team in ('A','B','C','D') having count(distinct u.team)=1),m.created_by,coalesce(m.created_at,now()),coalesce(m.created_at,now()) from public.daily_memos m;
create trigger team_memos_change_history_trigger after insert or update or delete on private.team_memos for each row execute function private.record_memo_change();
create function public.app_session_team_memo_write(p_token_hash text,p_date date,p_memo text,p_memo_id bigint default null,p_revision bigint default null)
returns jsonb language plpgsql security definer set search_path='' as $$
declare s jsonb; team text; uid bigint; row private.team_memos;
begin
 s:=public.app_session_verify(p_token_hash);
 if s->>'status' is distinct from 'ok' then return jsonb_build_object('status','invalid');end if;
 if coalesce(s->'user'->>'role','') not in ('user','team_admin','admin') then return jsonb_build_object('status','forbidden');end if;
 team:=s->'user'->>'team';uid:=(s->'user'->>'id')::bigint;
 if team is null or team not in ('A','B','C','D') then return jsonb_build_object('status','forbidden');end if;
 if p_date is null or not isfinite(p_date) or p_memo is null or char_length(p_memo)>500 then return jsonb_build_object('status','bad_input');end if;
 perform set_config('app.audit_actor_id',uid::text,true);perform set_config('app.audit_actor_name',s->'user'->>'name',true);
 perform pg_advisory_xact_lock(hashtextextended('team-memo:'||p_date||':'||team,0));
 if p_memo_id is null then
  if btrim(p_memo)='' then return jsonb_build_object('status','ok');end if;
  if exists(select 1 from private.team_memos m where m.date=p_date and m.owner_team=team) then return jsonb_build_object('status','conflict');end if;
  insert into private.team_memos(date,memo,owner_team,created_by) values(p_date,p_memo,team,s->'user'->>'name');
 else
  select * into row from private.team_memos m where m.id=p_memo_id for update;
  if not found then return jsonb_build_object('status','conflict');end if;
  if row.owner_team is distinct from team then return jsonb_build_object('status','forbidden');end if;
  if row.date<>p_date or p_revision is null or row.revision<>p_revision then return jsonb_build_object('status','conflict');end if;
  if btrim(p_memo)='' then delete from private.team_memos where id=row.id;
  else update private.team_memos set memo=p_memo,revision=revision+1,updated_at=now() where id=row.id;
  end if;
 end if;
 return jsonb_build_object('status','ok');
end $$;
revoke all on function public.app_session_team_memo_write(text,date,text,bigint,bigint) from public,anon,authenticated;
grant execute on function public.app_session_team_memo_write(text,date,text,bigint,bigint) to service_role;
-- Compatibility: old app pages can only edit a single memo belonging to their own team.
create or replace function public.app_session_memo_write(p_token_hash text,p_date date,p_memo text)
returns jsonb language plpgsql security definer set search_path='' as $$
declare s jsonb; row private.team_memos; n integer;
begin
 s:=public.app_session_verify(p_token_hash);if s->>'status' is distinct from 'ok' then return jsonb_build_object('status','invalid');end if;
 select count(*) into n from private.team_memos where date=p_date;
 if n>1 then return jsonb_build_object('status','conflict');end if;
 select * into row from private.team_memos where date=p_date;
 if found then
  if row.owner_team is distinct from (s->'user'->>'team') then return jsonb_build_object('status','forbidden');end if;
  return public.app_session_team_memo_write(p_token_hash,p_date,p_memo,row.id,row.revision);
 end if;
 return public.app_session_team_memo_write(p_token_hash,p_date,p_memo);
end $$;

CREATE OR REPLACE FUNCTION public.app_schedule_share_calendar(p_share_hash text, p_month text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare u public.app_users; start_day date; end_day date;
begin
 if p_share_hash is null or p_share_hash !~ '^[0-9a-f]{64}$' then return jsonb_build_object('status','invalid'); end if;
 select a.* into u from private.schedule_shares s join public.app_users a on a.id=s.user_id where s.token_hash=p_share_hash and s.revoked_at is null and a.is_active;
 if not found then return jsonb_build_object('status','invalid'); end if;
 if p_month is null or p_month !~ '^20[0-9]{2}-(0[1-9]|1[0-2])$' then return jsonb_build_object('status','bad_input'); end if;
 start_day:=(p_month||'-01')::date-7;end_day:=(p_month||'-01')::date+interval '1 month 7 days';
 return jsonb_build_object('status','ok','name',u.name,'team',u.team,
 'requests',coalesce((select jsonb_agg(jsonb_build_object('id',r.id,'requested_by',r.requested_by,'requested_by_id',r.requested_by_id,'team',r.team,'shift_type',r.shift_type,'shift_date',r.shift_date,'filled_by',r.filled_by,'filled_by_id',r.filled_by_id,'status',r.status,'reason',r.reason,'request_kind',r.request_kind,'helper_team',coalesce((select a.team from public.app_users a where a.id=r.filled_by_id),(select max(a.team) from public.app_users a where a.name=r.filled_by having count(*)=1))) order by r.shift_date,r.id) from public.requests r where r.shift_date>=start_day and r.shift_date<end_day),'[]'::jsonb),
 'memos',coalesce((select jsonb_agg(jsonb_build_object('id',m.id::text,'date',m.date,'memo',m.memo,'owner_team',m.owner_team,'revision',m.revision) order by m.date) from private.team_memos m where m.date>=start_day and m.date<end_day),'[]'::jsonb));
end $function$
;

CREATE OR REPLACE FUNCTION public.app_session_calendar_read(p_token_hash text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE s jsonb;
BEGIN
  s := public.app_session_verify(p_token_hash);
  IF s->>'status' IS DISTINCT FROM 'ok' THEN RETURN jsonb_build_object('status','invalid'); END IF;
  IF (s->'user'->>'role') IS NULL OR (s->'user'->>'role') NOT IN ('user','team_admin','admin') THEN RETURN jsonb_build_object('status','forbidden'); END IF;
  RETURN jsonb_build_object('status','ok',
    'requests',coalesce((SELECT jsonb_agg(to_jsonb(r) || jsonb_build_object('helper_team',
      coalesce((SELECT u.team FROM public.app_users u WHERE u.id=r.filled_by_id),
               (SELECT max(u.team) FROM public.app_users u WHERE u.name=r.filled_by HAVING count(*)=1)))
      ORDER BY r.shift_date,r.id) FROM public.requests r),'[]'::jsonb),
    'memos',coalesce((SELECT jsonb_agg(jsonb_build_object('id',m.id::text,'date',m.date,'memo',m.memo,'owner_team',m.owner_team,'revision',m.revision) ORDER BY m.date) FROM private.team_memos m),'[]'::jsonb));
END $function$
;

CREATE OR REPLACE FUNCTION public.app_session_calendar_read_range(p_token_hash text, p_start_date date, p_end_date date)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE s jsonb;
BEGIN
  s := public.app_session_verify(p_token_hash);
  IF s->>'status' IS DISTINCT FROM 'ok' THEN RETURN jsonb_build_object('status','invalid'); END IF;
  IF (s->'user'->>'role') IS NULL OR (s->'user'->>'role') NOT IN ('user','team_admin','admin') THEN RETURN jsonb_build_object('status','forbidden'); END IF;
  IF p_start_date IS NULL OR p_end_date IS NULL OR NOT isfinite(p_start_date) OR NOT isfinite(p_end_date) OR p_end_date<=p_start_date OR p_end_date-p_start_date>31 THEN RETURN jsonb_build_object('status','bad_input'); END IF;
  RETURN jsonb_build_object('status','ok',
    'requests',coalesce((SELECT jsonb_agg(to_jsonb(r) || jsonb_build_object('helper_team',
      coalesce((SELECT u.team FROM public.app_users u WHERE u.id=r.filled_by_id),
               (SELECT max(u.team) FROM public.app_users u WHERE u.name=r.filled_by HAVING count(*)=1)))
      ORDER BY r.shift_date,r.id) FROM public.requests r WHERE r.shift_date>=p_start_date AND r.shift_date<p_end_date),'[]'::jsonb),
    'memos',coalesce((SELECT jsonb_agg(jsonb_build_object('id',m.id::text,'date',m.date,'memo',m.memo,'owner_team',m.owner_team,'revision',m.revision) ORDER BY m.date) FROM private.team_memos m WHERE m.date>=p_start_date AND m.date<p_end_date),'[]'::jsonb));
END $function$
;
